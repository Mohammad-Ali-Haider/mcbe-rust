//! Small original loading-screen font, independent of installed resource packs.
use mcbe_core::textures::Texture;
pub fn texture() -> Texture {
    let mut rgba = vec![0; 128 * 128 * 4];
    for n in 0u8..=127 {
        for (y, row) in glyph(n.to_ascii_uppercase()).iter().enumerate() {
            for x in 0..5 {
                if row & (1 << (4 - x)) != 0 {
                    let i = ((usize::from(n) / 16 * 8 + y) * 128 + usize::from(n) % 16 * 8 + x) * 4;
                    rgba[i..i + 4].copy_from_slice(&[255; 4]);
                }
            }
        }
    }
    Texture {
        width: 128,
        height: 128,
        rgba,
    }
}
